"""Merge per-candidate results into the published dataset layout and a trial summary."""

from __future__ import annotations

import json
import shutil
import statistics
from collections import Counter
from pathlib import Path

from . import sources

ATTRIBUTION = """# python-bug-harvest output

Rebuilt, test-verified Python bug tasks. Generated by https://github.com/Vikas18597/python-bug-harvest

## Layout
- `harvest.jsonl` - one SWE-bench-style row per verified bug (see the repository README for fields).
- `snapshots/<instance_id>.tar.gz` - source tree at `base_commit` (`git archive`, no `.git`).
- `rejections.jsonl` - every rejected candidate with its rejection category and per-tier attempts.
- `summary.json` / `summary.md` - trial statistics.

## Sources and licences
Rows are derived from the following datasets; the `source*` fields on every row say which one.
{sources}

Snapshot tarballs contain third-party source code under each project's own licence
(recorded per row in `repo_license`).
"""


def _source_lines() -> str:
    return "\n".join(
        f"- {s.hf_repo} (revision `{s.revision}`), licence {s.licence}, https://huggingface.co/datasets/{s.hf_repo}"
        for s in sources.SOURCES.values()
    )


def aggregate(results_dir: Path, out_dir: Path, *, candidates_total: int | None = None) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    snaps = out_dir / "snapshots"
    snaps.mkdir(exist_ok=True)
    results = []
    for path in sorted(results_dir.glob("*/result.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        iid = path.parent.name
        if result.get("instance_id") != iid or (
                result.get("verified") and (result.get("snapshot") or {}).get("file") != f"{iid}.tar.gz"):
            result.update(instance_id=iid, verified=False, reason="invalid_result")
        result["_dir"] = path.parent
        results.append(result)

    verified, rejected = [], []
    with open(out_dir / "harvest.jsonl", "w", encoding="utf-8") as tasks, \
            open(out_dir / "rejections.jsonl", "w", encoding="utf-8") as rej:
        for r in results:
            d = r.pop("_dir")
            if r["verified"] and (d / "task.json").exists():
                tasks.write((d / "task.json").read_text(encoding="utf-8").strip() + "\n")
                shutil.copy(d / r["snapshot"]["file"], snaps / r["snapshot"]["file"])
                verified.append(r)
            else:
                rej.write(json.dumps({
                    "instance_id": r["instance_id"], "repo": r.get("repo"), "reason": r["reason"],
                    "attempts": [{k: a.get(k) for k in ("tier", "python", "reason", "verdict", "install_steps")}
                                 for a in r.get("attempts", [])],
                    "error": r.get("error"),
                }) + "\n")
                rejected.append(r)

    walls = [r["wall_seconds"] for r in results]
    sizes = [r["snapshot"]["bytes"] for r in verified]
    summary = {
        "candidates": candidates_total if candidates_total is not None else len(results),
        "results": len(results),
        "verified": len(verified),
        "rejected": len(rejected),
        "missing_results": (candidates_total - len(results)) if candidates_total is not None else 0,
        "rejection_reasons": dict(Counter(r["reason"] for r in rejected).most_common()),
        "python_versions": dict(Counter(r.get("python_version") for r in verified).most_common()),
        "tiers": dict(Counter(r.get("tier") for r in verified).most_common()),
        "wall_seconds": {
            "total": round(sum(walls), 1),
            "mean": round(statistics.mean(walls), 1) if walls else 0,
            "median": round(statistics.median(walls), 1) if walls else 0,
            "max": max(walls) if walls else 0,
        },
        "snapshot_bytes": {
            "mean": round(statistics.mean(sizes)) if sizes else 0,
            "median": round(statistics.median(sizes)) if sizes else 0,
            "total": sum(sizes),
        },
        "per_candidate": [
            {"instance_id": r["instance_id"], "verified": r["verified"], "reason": r["reason"],
             "python": r.get("python_version"), "tier": r.get("tier"), "wall_seconds": r["wall_seconds"],
             "snapshot_bytes": (r.get("snapshot") or {}).get("bytes")}
            for r in sorted(results, key=lambda x: x["instance_id"])
        ],
    }
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (out_dir / "summary.md").write_text(render_markdown(summary), encoding="utf-8")
    (out_dir / "README.md").write_text(ATTRIBUTION.format(sources=_source_lines()), encoding="utf-8")
    return summary


def render_markdown(s: dict) -> str:
    lines = [
        f"**Verified {s['verified']} / {s['candidates']}** candidates "
        f"(rejected {s['rejected']}, missing results {s['missing_results']}).",
        "",
        "| Rejection reason | Count |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in s["rejection_reasons"].items()],
        "",
        f"Wall time per bug: mean {s['wall_seconds']['mean']}s, median {s['wall_seconds']['median']}s, "
        f"max {s['wall_seconds']['max']}s; total {s['wall_seconds']['total']}s.",
        f"Snapshot size: mean {s['snapshot_bytes']['mean'] / 1e6:.2f} MB, total {s['snapshot_bytes']['total'] / 1e6:.2f} MB.",
        f"Python versions used: {s['python_versions']}; tiers: {s['tiers']}.",
        "",
        "| Candidate | Result | Python | Wall s | Snapshot MB |",
        "|---|---|---|---|---|",
    ]
    for c in s["per_candidate"]:
        size = f"{c['snapshot_bytes'] / 1e6:.2f}" if c["snapshot_bytes"] else ""
        result = "verified" if c["verified"] else c["reason"]
        lines.append(f"| {c['instance_id']} | {result} | {c['python'] or ''} | {c['wall_seconds']} | {size} |")
    return "\n".join(lines) + "\n"
